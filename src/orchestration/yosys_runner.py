"""Yosys synthesis runner with automated script generation and metrics extraction."""

from pathlib import Path
from typing import List, Dict, Any, Optional
import hashlib

from src.common.types import ExecutionResult, ToolType, StageName, ParsedMetric
from src.common.exceptions import ConfigurationError, RTLValidationError
from src.orchestration.tool_runner import ToolRunner
from src.log_intelligence.yosys_parser import YosysLogParser
from src.common.logger import logger


class YosysRunner:
    """Automates RTL synthesis using Yosys."""

    def __init__(self, runner: Optional[ToolRunner] = None, yosys_binary: str = "yosys"):
        self.runner = runner or ToolRunner()
        self.binary = yosys_binary
        self.parser = YosysLogParser()

    def generate_script(
        self,
        verilog_files: List[Path],
        top_module: str,
        output_netlist: Path,
        pdk: str = "generic",
        liberty_path: Optional[str] = None,
        flatten: bool = True
    ) -> str:
        """Generate a reproducible Yosys TCL/command script."""
        lines = []
        lines.append(f"# Autogenerated by EDA-Genius YosysRunner")
        lines.append(f"# Top Module: {top_module}")
        lines.append(f"# Target PDK: {pdk}")

        for vf in verilog_files:
            v_conv = self.runner._convert_path(vf)
            lines.append(f'read_verilog -sv "{v_conv}"')

        lines.append(f"hierarchy -check -top {top_module}")

        if pdk == "sky130hd" and liberty_path:
            lib_conv = self.runner._convert_path(Path(liberty_path))
            lines.append(f"synth -top {top_module}")
            lines.append(f'dfflibmap -liberty "{lib_conv}"')
            lines.append(f'abc -liberty "{lib_conv}"')
            lines.append(f'stat -liberty "{lib_conv}"')
        else:
            # High-performance generic synthesis
            lines.append(f"synth -top {top_module}")
            if flatten:
                lines.append("flatten")
            lines.append(f"stat -top {top_module}")

        out_conv = self.runner._convert_path(output_netlist)
        lines.append(f'write_verilog -noattr "{out_conv}"')

        return "\n".join(lines) + "\n"

    def synthesize(
        self,
        verilog_files: List[Path],
        top_module: str,
        workdir: Path,
        pdk: str = "generic",
        liberty_path: Optional[str] = None,
        timeout_s: int = 1800
    ) -> tuple[ExecutionResult, List[ParsedMetric]]:
        """Run synthesis flow end-to-end, capture logs, and extract parsed metrics."""
        # 1. Validate inputs
        if not verilog_files:
            raise ConfigurationError("No Verilog files provided for synthesis")
        for vf in verilog_files:
            if not vf.exists():
                raise ConfigurationError(f"RTL source file does not exist: {vf}")
            if vf.suffix.lower() not in [".v", ".sv"]:
                raise ConfigurationError(f"Invalid file extension {vf.suffix} for RTL file: {vf}")

        workdir.mkdir(parents=True, exist_ok=True)
        script_path = workdir / "synth.ys"
        netlist_path = workdir / f"{top_module}_synth.v"
        stdout_path = workdir / "yosys.log"
        stderr_path = workdir / "yosys.err"

        # 2. Generate and write script
        script_content = self.generate_script(
            verilog_files=verilog_files,
            top_module=top_module,
            output_netlist=netlist_path,
            pdk=pdk,
            liberty_path=liberty_path
        )
        with open(script_path, "w", encoding="utf-8") as f:
            f.write(script_content)

        # 3. Execute
        script_conv = self.runner._convert_path(script_path)
        command = [self.binary, "-s", script_conv]

        result = self.runner.execute(
            command=command,
            workdir=workdir,
            stdout_path=stdout_path,
            stderr_path=stderr_path,
            tool=ToolType.YOSYS,
            stage=StageName.SYNTHESIS,
            timeout_s=timeout_s
        )

        # 4. Attach generated netlist artifact
        if netlist_path.exists():
            result.artifact_paths["netlist_v"] = str(netlist_path.resolve())

        # 5. Parse log for cell counts and metrics
        metrics = self.parser.parse_file(stdout_path)

        return result, metrics
